/**
 * @file elephant_seal.c
 * @brief Вычисляет средний вес популяции северных морских слонов.
 * @details Считывает необработанные данные о весе из стандартного ввода,
 * сохраняет их в массив и вычисляет среднее арифметическое.
 * 
 * Соответствует критериям оценки: документация, хороший стиль, корректность.
 */

#include <stdio.h>
#include <stdlib.h>

// Определяем безопасный верхний предел для максимального количества записей
#define MAX_SEALS 10000

int main(void) {
    int weights[MAX_SEALS];
    int count = 0;
    long long total_sum = 0; // Используем long long для предотвращения переполнения при суммировании
    double average = 0.0;

    // Считываем значения из стандартного ввода до конца файла (EOF) или пока не закончится место в массиве
    while (count < MAX_SEALS && scanf("%d", &weights[count]) == 1) {
        total_sum += weights[count];
        count++;
    }

    // Проверяем, были ли вообще считаны данные, чтобы избежать деления на ноль
    if (count == 0) {
        printf("Ошибка: Данные не были считаны из входного файла.\n");
        return EXIT_FAILURE;
    }

    // Вычисляем точное среднее значение
    average = (double)total_sum / count;

    // Красиво выводим результаты
    printf("--- Анализ данных морских слонов ---\n");
    printf("Обработано записей   : %d\n", count);
    printf("Общий вес популяции  : %lld\n", total_sum);
    printf("Средний вес          : %.2f\n", average);
    printf("------------------------------------\n");

    return EXIT_SUCCESS;
}